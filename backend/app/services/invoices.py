PRIVATE_FIELDS = {"_id", "enc_key_wrapped"}
MARKET_STATES = {"FINANCING_REQUESTED"}
FINANCIER_VISIBLE = {"FINANCING_REQUESTED", "FINANCED", "REPAID", "CLOSED"}


def new_id() -> str:
    return "inv_" + uuid.uuid4().hex[:12]


# --------------------------------------------------------------------------- documents
async def store_document(data: bytes, mime: str, filename: str) -> Dict[str, Any]:
    doc_hash = crypto.sha256_hex(data)
    key = crypto.new_data_key()
    blob = crypto.encrypt(data, key, aad=bytes.fromhex(doc_hash[2:]))
    cid = await ipfs.pin(blob, filename)
    return {"doc_hash": doc_hash, "cid": cid, "enc_key_wrapped": crypto.wrap_key(key), "mime": mime,
            "file_name": filename, "size": len(data)}


async def load_document(doc: Dict[str, Any]) -> bytes:
    blob = await ipfs.fetch(doc["cid"])
    key = crypto.unwrap_key(doc["enc_key_wrapped"])
    data = crypto.decrypt(blob, key, aad=bytes.fromhex(doc["doc_hash"][2:]))
    if crypto.sha256_hex(data) != doc["doc_hash"]:
        raise HTTPException(500, "Document integrity check failed.")
    return data


def render_manual_pdf(fields: Dict[str, Any], supplier_name: str) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.pdfgen import canvas

    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    w, h = A4
    c.setFont("Helvetica-Bold", 20)
    c.drawString(20 * mm, h - 25 * mm, supplier_name or fields.get("supplier_name") or "Supplier")
    c.setFont("Helvetica-Bold", 22)
    c.drawRightString(w - 20 * mm, h - 25 * mm, "INVOICE")
    c.setFont("Helvetica", 11)
    y = h - 50 * mm
    rows = [("Invoice No", fields.get("invoice_number")), ("Invoice Date", fields.get("invoice_date")),
            ("Due Date", fields.get("due_date")), ("Bill To", fields.get("buyer_name")),
            ("Description", fields.get("description"))]
    for k, v in rows:
        c.drawString(20 * mm, y, f"{k}: {v or ''}"[:110])
        y -= 8 * mm
    c.setFont("Helvetica-Bold", 14)
    c.drawString(20 * mm, y - 6 * mm, f"Grand Total: $ {float(fields.get('amount') or 0):,.2f}")
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(20 * mm, 20 * mm, "Generated by InvoChain from manually entered data.")
    c.save()
    return buf.getvalue()


# --------------------------------------------------------------------------- views / access
def can_view(doc: Dict[str, Any], user: Dict[str, Any]) -> bool:
    role, w = user["role"], user["wallet"]
    if role == "admin":
        return True
    if role == "supplier":
        return doc["supplier_wallet"] == w
    if role == "buyer":
        return doc.get("buyer_wallet") == w and doc["status"] != "DRAFT"
    if role == "financier":
        return doc["status"] in FINANCIER_VISIBLE and (doc["status"] in MARKET_STATES or doc.get("financier_wallet") == w)
    return False


def view(doc: Dict[str, Any], user: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    out = {k: v for k, v in doc.items() if k not in PRIVATE_FIELDS}
    if user and user["role"] == "financier":  # financiers do not see raw extraction details / full trace
        a = out.get("analysis") or {}
        out["analysis"] = {"risk": a.get("risk"), "eligibility": a.get("eligibility"), "summary": a.get("summary"),
                           "fraud": {"signals": [{k: v for k, v in s.items() if k != "forces_high"} for s in (a.get("fraud") or {}).get("signals", [])]}}
    for k, v in list(out.items()):
        if isinstance(v, datetime):
            out[k] = v.isoformat() + "Z"
    return out


async def get_invoice_or_404(invoice_id: str) -> Dict[str, Any]:
    doc = await get_db().invoices.find_one({"id": invoice_id}, {"_id": 0})
    if not doc:
        raise HTTPException(404, "Invoice not found.")
    return doc


# --------------------------------------------------------------------------- chain mirroring
def _apply_chain_state(doc: Dict[str, Any], oc: Dict[str, Any]) -> Dict[str, Any]:
    st = oc["status"]
    upd = {
        "chain_id": oc["chain_id"], "status": st, "on_chain": True, "risk_tier_on_chain": oc["risk"],
        "extra_verified": oc["extra_verified"], "token_id": oc["chain_id"] if st in ("VERIFIED", "FINANCING_REQUESTED", "FINANCED", "REPAID", "FLAGGED") else None,
        "token_locked": st in ("FINANCING_REQUESTED", "FINANCED", "REPAID"),
        "financier_wallet": oc["financier"], "advance_bps": oc["advance_bps"],
        "financed_amount": from_units(oc["financed_amount_units"]) if oc["financed_amount_units"] else None,
        "repay_amount": from_units(oc["repay_amount_units"]) if oc["repay_amount_units"] else None,
        "repaid_amount": from_units(oc["repaid_amount_units"]),
        "financed_at": datetime.utcfromtimestamp(oc["financed_at"]) if oc["financed_at"] else None,
        "repaid_at": datetime.utcfromtimestamp(oc["repaid_at"]) if oc["repaid_at"] else None,
        "status_before_flag": oc["status_before_flag"] if st == "FLAGGED" else None,
        "updated_at": datetime.utcnow(),
    }
    if st == "FINANCING_REQUESTED":
        upd["advance_amount"] = from_units(oc["amount_units"] * oc["advance_bps"] // 10_000)
    return upd


async def mirror_invoice(chain_id: int, *, doc: Optional[Dict[str, Any]] = None) -> Optional[Dict[str, Any]]:
    """Reads the on-chain truth for one invoice and mirrors it into MongoDB."""
    db = get_db()
    oc = await run(chain().get_invoice, chain_id)
    if doc is None:
        doc = await db.invoices.find_one({"chain_id": chain_id}, {"_id": 0}) or await db.invoices.find_one({"doc_hash": oc["doc_hash"], "supplier_wallet": oc["supplier"]}, {"_id": 0})
    if not doc:
        log.info("On-chain invoice %s has no matching DB record", chain_id)
        return None
    await db.invoices.update_one({"id": doc["id"]}, {"$set": _apply_chain_state(doc, oc)})
    return await db.invoices.find_one({"id": doc["id"]}, {"_id": 0})


def risk_report_hash(doc: Dict[str, Any]) -> str:
    r = (doc.get("analysis") or {}).get("risk") or {}
    canon = json.dumps({"score": r.get("score"), "tier": r.get("tier"), "assessed_at": r.get("assessed_at"),
                        "factors": [(f["id"], f["points"]) for f in r.get("factors", [])],
                        "model": (r.get("model") or {}).get("model_version"), "invoice": doc["doc_hash"]}, sort_keys=True)
    return "0x" + Web3.keccak(text=canon).hex().removeprefix("0x")


async def anchor_risk(doc: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """Operator wallet records the (advisory) AI risk tier + report hash on-chain. Idempotent."""
    if doc.get("risk_anchor_tx") or doc.get("chain_id") is None:
        return None
    tier = ((doc.get("analysis") or {}).get("risk") or {}).get("tier")
    if tier not in ("LOW", "MEDIUM", "HIGH"):
        return None
    try:
        tx = await run(chain().op_set_risk, doc["chain_id"], tier, risk_report_hash(doc))
    except Exception as e:  # noqa: BLE001
        log.warning("anchor_risk failed for %s: %s", doc["id"], e)
        await get_db().invoices.update_one({"id": doc["id"]}, {"$set": {"risk_anchor_error": str(e)[:300]}})
        return None
    await get_db().invoices.update_one({"id": doc["id"]}, {"$set": {"risk_anchor_tx": tx["hash"], "risk_anchor_error": None}})
    await record_tx(tx["hash"], doc, "RiskAssessmentRecorded", chain().operator.address.lower(), tx["block"])
    return tx


async def record_tx(tx_hash: str, doc: Optional[Dict[str, Any]], kind: str, sender: str, block: int,
                    timestamp: Optional[int] = None, success: bool = True, gas_used: Optional[int] = None,
                    events: Optional[List[str]] = None) -> None:
    await get_db().chain_txs.update_one(
        {"hash": tx_hash.lower()},
        {"$set": {"hash": tx_hash.lower(), "kind": kind, "from": sender.lower(), "block": block, "success": success,
                  "gas_used": gas_used, "events": events or [kind],
                  "invoice_id": doc["id"] if doc else None, "invoice_number": doc.get("invoice_number") if doc else None,
                  "chain_invoice_id": doc.get("chain_id") if doc else None,
                  "parties": [w for w in [doc.get("supplier_wallet"), doc.get("buyer_wallet"), doc.get("financier_wallet")] if w] if doc else [],
                  "at": datetime.utcfromtimestamp(timestamp) if timestamp else datetime.utcnow()}},
        upsert=True)


async def process_tx(tx_hash: str) -> Dict[str, Any]:
    """Reads a mined tx from the chain, mirrors every invoice it touched, anchors AI risk where needed."""
    info = await run(chain().get_receipt, tx_hash)
    if info is None:
        return {"pending": True}
    db = get_db()
    touched: List[str] = []
    ids = []
    for ev in info["events"]:
        iid = ev["args"].get("invoiceId")
        if iid is not None and iid not in ids:
            ids.append(iid)
    registered = {e["args"]["invoiceId"]: e["args"] for e in info["events"] if e["name"] == "InvoiceRegistered"}
    last_doc = None
    for iid in ids:
        doc = None
        if iid in registered:  # link DB record <-> chain id via the document hash
            a = registered[iid]
            doc = await db.invoices.find_one({"doc_hash": a["docHash"], "supplier_wallet": a["supplier"], "status": "DRAFT"}, {"_id": 0})
            if doc:
                await db.invoices.update_one({"id": doc["id"]}, {"$set": {"chain_id": iid, "registered_tx": info["hash"]}})
                doc["chain_id"] = iid
        mirrored = await mirror_invoice(iid, doc=doc)
        if mirrored:
            touched.append(mirrored["id"])
            last_doc = mirrored
            if iid in registered:
                await anchor_risk(mirrored)
                mirrored = await mirror_invoice(iid, doc=mirrored) or mirrored
    names = [e["name"] for e in info["events"]]
    kind = names[0] if names else ("ERC20_APPROVE" if not info["to_registry"] else "TRANSACTION")
    await record_tx(info["hash"], last_doc, kind, info["from"], info["block"], info["timestamp"], info["success"], info["gas_used"], names)
    return {"pending": False, "success": info["success"], "events": names, "invoice_ids": touched, "block": info["block"]}


async def reconcile() -> Dict[str, int]:
    """View-call-only reconciliation (works on free RPC tiers that limit eth_getLogs ranges)."""
    db = get_db()
    updated = 0
    open_docs = await db.invoices.find({"chain_id": {"$ne": None}, "status": {"$nin": list(TERMINAL)}}, {"_id": 0}).to_list(1000)
    for d in open_docs:
        before = d.get("status")
        m = await mirror_invoice(d["chain_id"], doc=d)
        if m and m.get("status") != before:
            updated += 1
    # discover registrations the browser never confirmed
    count = await run(chain().invoice_count)
    known = {d["chain_id"] for d in await db.invoices.find({"chain_id": {"$ne": None}}, {"chain_id": 1, "_id": 0}).to_list(5000)}
    for cid in range(1, count + 1):
        if cid not in known:
            m = await mirror_invoice(cid)
            if m:
                await anchor_risk(m)
                updated += 1
    return {"updated": updated, "on_chain_total": count}
